import type { CsvLanguage } from '../csv-sheet/types';

/**
 * The fixed words of every report export's Parameters sheet. They never show on a screen, so no
 * locale file holds them: the four languages are kept here.
 */
export interface ReportExportLabels {
  /** The name of the sheet. */
  parameters: string;
  parameter: string;
  value: string;
  generatedOn: string;
  generatedBy: string;
  /** A parameter of the reports that read days in the user's zone. */
  timeZone: string;
  /** The line a person under data-scoped access gets: the figures cover what they may read. */
  computedOnYourAccess: string;
}

/**
 * A label template with its placeholder filled (`{{metric}} amount`): the value goes in as is, a `$` in it
 * included (a string replacement would read `$&` or `$$` as patterns).
 */
export function fillLabel(template: string, placeholder: string, value: string): string {
  return template.replace(`{{${placeholder}}}`, () => value);
}

