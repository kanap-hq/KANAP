/**
 * Renders the files the variable registry produces (`env-registry.ts`): the on-premise example
 * `.env` and the example block of the on-premise configuration page, in each language of the
 * manual. Pure: the files are read and written by `scripts/generate-env-reference.ts`, and
 * compared by `config/__tests__/env-registry.spec.ts`.
 */
import {
  ENV_EXAMPLE_SECTIONS,
  ENV_LABELS,
  ENV_LANGUAGES,
  ENV_REGISTRY,
  EnvExampleSection,
  EnvLanguage,
  EnvVariable,
  envDescription,
  envText,
} from './env-registry';

/** Paths from the root of the repository. */
export const ONPREM_EXAMPLE_FILE = 'infra/.env.onprem.example';
export const manualConfigurationFile = (language: EnvLanguage): string => `doc/help/docs/${language}/on-premise/configuration.md`;

export const MANUAL_BLOCK_START =
  '<!-- env-example:start. Generated by "npm run env:generate" in backend/ from backend/src/config/env-registry.ts: change the registry, not this block. -->';
export const MANUAL_BLOCK_END = '<!-- env-example:end -->';

const WIDTH = 100;

const EXAMPLE_HEADER = [
  '# =============================================================================',
  '# Kadratis On-Premise Configuration',
  '# Copy this file to ../.env (the repository root) and fill in the values:',
  '#   cp infra/.env.onprem.example .env && chmod 600 .env',
  '# The file holds every secret of the installation: keep it readable by its owner only.',
  '# See doc/help/docs/en/on-premise/configuration.md for the full reference.',
  '# After a change, apply it with: docker compose -f infra/compose.onprem.yml up -d api',
  '# Generated by "npm run env:generate" in backend/ from backend/src/config/env-registry.ts:',
  '# change the registry, not this file.',
  '# =============================================================================',
];

const RULE = '# =============================================================================';

/** The variables a section writes, in the order of the registry. */
export function sectionVariables(section: EnvExampleSection): EnvVariable[] {
  return ENV_REGISTRY.filter((variable) => variable.example.state !== 'absent' && variable.example.section === section.id);
}

/** Words of a text as `# ` lines of at most WIDTH characters. */
export function commentLines(text: string): string[] {
  const lines: string[] = [];
  let current = '';
  for (const word of text.split(/\s+/).filter(Boolean)) {
    if (current && `# ${current} ${word}`.length > WIDTH) {
      lines.push(`# ${current}`);
      current = word;
    } else {
      current = current ? `${current} ${word}` : word;
    }
  }
  if (current) lines.push(`# ${current}`);
  return lines;
}

function variableLine(variable: EnvVariable): string {
  if (variable.example.state === 'absent') throw new Error(`${variable.name} is not in the example`);
  const line = `${variable.name}=${variable.example.value}`;
  return variable.example.state === 'active' ? line : `# ${line}`;
}

function sectionTitle(section: EnvExampleSection, language: EnvLanguage): string {
  return envText(ENV_LABELS.sections[section.id]?.title, language);
}

/** `infra/.env.onprem.example`: titles, comments and variables in English. */
export function renderOnPremExample(): string {
  const lines = [...EXAMPLE_HEADER];
  for (const section of ENV_EXAMPLE_SECTIONS) {
    const variables = sectionVariables(section);
    if (variables.length === 0) continue;
    lines.push('', `# ${sectionTitle(section, 'en')}`, ...section.comment.map((line) => `# ${line}`.trimEnd()));
    for (const variable of variables) {
      const example = variable.example;
      const comment = example.state !== 'absent' && example.comment
        ? example.comment.map((line) => `# ${line}`.trimEnd())
        : section.describeEntries ? commentLines(envDescription(variable.name, 'en')) : [];
      lines.push(...comment, variableLine(variable));
    }
  }
  return `${lines.join('\n')}\n`;
}

/** The block of the manual in one language, markers included: titles and notes translated. */
export function renderManualBlock(language: EnvLanguage): string {
  const lines = [MANUAL_BLOCK_START, '```bash', RULE, `# ${envText(ENV_LABELS.block.header, language)}`, RULE];
  for (const section of ENV_EXAMPLE_SECTIONS) {
    const variables = sectionVariables(section);
    if (variables.length === 0) continue;
    const note = envText(ENV_LABELS.sections[section.id]?.note, language);
    lines.push('', `# ${sectionTitle(section, language)}`, ...(note ? commentLines(note) : []), ...variables.map(variableLine));
  }
  lines.push('```', MANUAL_BLOCK_END);
  return lines.join('\n');
}

/** The page with its block replaced. Throws when the page has not exactly one pair of markers. */
export function replaceManualBlock(page: string, block: string): string {
  const start = page.indexOf(MANUAL_BLOCK_START);
  const end = page.indexOf(MANUAL_BLOCK_END);
  if (start < 0 || end < start || page.indexOf(MANUAL_BLOCK_START, start + 1) >= 0 || page.indexOf(MANUAL_BLOCK_END, end + 1) >= 0) {
    throw new Error('the page needs one start marker and one end marker of the generated block, in that order');
  }
  return page.slice(0, start) + block + page.slice(end + MANUAL_BLOCK_END.length);
}

/**
 * Every produced file, from the current content of the pages (`read` takes a repository path).
 * Throws, naming the page, when a page lacks its pair of markers.
 */
export function renderEnvReferenceFiles(read: (file: string) => string): { file: string; content: string }[] {
  return [
    { file: ONPREM_EXAMPLE_FILE, content: renderOnPremExample() },
    ...ENV_LANGUAGES.map((language) => {
      const file = manualConfigurationFile(language);
      try {
        return { file, content: replaceManualBlock(read(file), renderManualBlock(language)) };
      } catch (error) {
        throw new Error(`${file}: ${error instanceof Error ? error.message : String(error)}`);
      }
    }),
  ];
}

export type EnvReferenceCommandIo = {
  /** Reads and writes a file by its repository path. */
  read: (file: string) => string;
  write: (file: string, content: string) => void;
  log: (line: string) => void;
  error: (line: string) => void;
};

/**
 * `npm run env:generate` (`scripts/generate-env-reference.ts`): writes the files that differ, or
 * with `check` names them and writes nothing. Returns the exit code; a page it cannot render is
 * one readable line, with no stack trace.
 */
export function runEnvReferenceCommand(check: boolean, io: EnvReferenceCommandIo): number {
  let files: { file: string; content: string }[];
  try {
    files = renderEnvReferenceFiles(io.read);
  } catch (error) {
    io.error(error instanceof Error ? error.message : String(error));
    return 1;
  }
  const differing = files.filter(({ file, content }) => io.read(file) !== content);
  if (check) {
    for (const { file } of differing) io.error(`${file} differs from the registry: run "npm run env:generate" in backend/.`);
    if (differing.length === 0) io.log('The example .env and the manual blocks match the registry.');
    return differing.length === 0 ? 0 : 1;
  }
  for (const { file, content } of differing) {
    io.write(file, content);
    io.log(`Wrote ${file}`);
  }
  if (differing.length === 0) io.log('Nothing to write: the files match the registry.');
  return 0;
}
