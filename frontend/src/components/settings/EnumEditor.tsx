// Base type for all enum items. The code is generated by the server from the name and never edited here.
export interface EnumItem {
  code: string;
  label: string;
  deprecated?: boolean;
  translations?: CatalogTranslations;
  localId?: string;
}

/** How a change is saved: a text after its delay (`type`), a choice at once (`choose`). */
export type EnumEditorChange = 'type' | 'choose';

/** What the editor knows about a row, for the cells. */
export interface EnumEditorCell {
  /** The name the rest of the application shows for the value, in the person's language. */
  shownName: string;
  /** A typed name: it becomes the base name, and the person's own translation of it goes. */
  rename: (text: string) => void;
  /** A value the server manages (lifecycle statuses): a line of text, never changed. */
  builtIn: boolean;
}

// Column definition for the editor
export interface EnumEditorColumn<T extends EnumItem> {
  key: keyof T | string;
  header: string;
  width?: string;
  align?: 'left' | 'center' | 'right';
  /** Orange asterisk on the column header (the Name column). */
  required?: boolean;
  render?: (
    item: T,
    onChange: (patch: Partial<T>, how?: EnumEditorChange) => void,
    isLocked: boolean,
    isFocused: boolean,
    focusRef: React.RefCallback<HTMLInputElement>,
    cell: EnumEditorCell,
  ) => React.ReactNode;
}

export interface EnumEditorProps<T extends EnumItem> {
  items: T[];
  /** The rows after a change, and how that change is saved. */
  onChange: (items: T[], how: EnumEditorChange) => void;
  /** A text field of the editor lost the focus: what waits can be sent. */
  onCommit?: () => void;
  columns?: EnumEditorColumn<T>[];
  /** Rows that cannot be edited nor removed (server-managed values). */
  lockedCodes?: string[];
  /** Rows that can be edited and retired but never removed (defaults the server re-adds). */
  protectedCodes?: string[];
  /** Catalog key for usage checks before removal; without it, rows are removed directly. */
  usageList?: string;
  /**
   * The list's shipped values: a value still as shipped shows its shipped translation, here as
   * everywhere else, and the translations dialog previews it.
   */
  defaults?: CatalogDefaults;
  /** Names of this list end up in a comma-separated CSV cell. */
  forbidComma?: boolean;
  /** The other fields of a new row (its defaults); the code and name start empty. */
  newRow?: () => Partial<T>;
  hideAddButton?: boolean;
  /** Example shown in the name field. Already translated. Absent means no example. */
  namePlaceholder?: string;
  /** Every value stays visible. Fields are locked and add, remove and translate are hidden. */
  readOnly?: boolean;
  addButtonLabel?: string;
  onAddRequest?: () => void;
  addRequestToken?: number;
  rowHeight?: number;
  emptyMessage?: string;
}

// Helper to generate local IDs
const makeLocalId = (prefix = 'enum') =>
  `${prefix}-${Math.random().toString(36).slice(2, 9)}-${Date.now().toString(36)}`;

// Ensure items have localIds - returns same reference if no changes needed
const withLocalIds = <T extends EnumItem>(items: T[], prefix = 'enum'): (T & { localId: string })[] => {
  const allHaveIds = items.every((item) => item.localId);
  if (allHaveIds) return items as (T & { localId: string })[];
  return items.map((item) => (item.localId ? item : { ...item, localId: makeLocalId(prefix) })) as (T & { localId: string })[];
};

/** The name a row shows: the workspace's translation, else the shipped one while untouched, else the name. */
export function shownCatalogName(item: EnumItem, locale: CatalogLocale, defaults?: CatalogDefaults): string {
  return localizeCatalogItem(item, locale, defaults).label;
}

/** A retyped name: it is the base name now, and the person's own translation of the name goes. */
export function renamedCatalogItem<T extends EnumItem>(item: T, text: string, locale: CatalogLocale): Partial<T> {
  const own = item.translations?.[locale];
  if (!own?.label) return { label: text } as Partial<T>;
  const { label: _dropped, ...rest } = own;
  const translations: CatalogTranslations = { ...item.translations };
  if (Object.keys(rest).length) translations[locale] = rest;
  else delete translations[locale];
  return { label: text, translations: Object.keys(translations).length ? translations : undefined } as Partial<T>;
}

const hasTypedTranslation = (item: EnumItem) => Object.values(item.translations ?? {}).some((entry) => !!entry?.label || !!entry?.description);

const issueTextSx = { fontSize: 11, color: 'kanap.text.tertiary', mt: 0.25 } as const;
const iconSx = { width: 26, height: 26, p: 0 } as const;
const tableSx = {
  '& .MuiTableCell-head': { fontSize: 11, fontWeight: 500, color: 'kanap.text.secondary', py: 0.75, px: 1 },
  '& .MuiTableCell-body': { py: 0.5, px: 1, verticalAlign: 'top', borderBottom: '1px solid', borderColor: 'kanap.border.default' },
} as const;

/** Name column shared by every editor: the visible identity of a value. */
export function nameColumn<T extends EnumItem>(t: TFunction, width = '40%', placeholder?: string): EnumEditorColumn<T> {
  return {
    key: 'label',
    header: t('enumEditor.name'),
    width,
    required: true,
    render: (item, onChange, isLocked, isFocused, focusRef, cell) => (cell?.builtIn ? (
      <Typography sx={{ fontSize: 13, color: 'kanap.text.primary', py: '4px' }}>{cell.shownName}</Typography>
    ) : (
      <TextField
        value={cell ? cell.shownName : item.label}
        onChange={(e) => (cell ? cell.rename(e.target.value) : onChange({ label: e.target.value } as Partial<T>))}
        size="small"
        fullWidth
        required
        placeholder={placeholder}
        disabled={isLocked}
        inputRef={isFocused ? focusRef : undefined}
        inputProps={{ 'aria-label': t('enumEditor.name') }}
        sx={tableCellTextFieldSx}
      />
    )),
  };
}

/** "Stop offering" column: the value stays on existing records and is not proposed any more. */
export function retiredColumn<T extends EnumItem>(t: TFunction, width = '20%'): EnumEditorColumn<T> {
  return {
    key: 'deprecated',
    header: t('enumEditor.noLongerOffered'),
    width,
    render: (item, onChange, isLocked, _isFocused, _focusRef, cell) => (cell?.builtIn ? null : (
      <Checkbox
        size="small"
        checked={!!item.deprecated}
        onChange={(e) => onChange({ deprecated: e.target.checked } as Partial<T>, 'choose')}
        disabled={isLocked}
        sx={{ p: '3px' }}
        inputProps={{ 'aria-label': `${t('enumEditor.noLongerOffered')} ${cell?.shownName ?? item.label}` }}
      />
    )),
  };
}

/** Hosting: on premises or in the cloud. */
