export type GraphTier = 'top' | 'upper' | 'center' | 'lower' | 'bottom';

const GRAPH_TIERS: GraphTier[] = ['top', 'upper', 'center', 'lower', 'bottom'];

/** Server roles and entities: their level in the connection graph. */
export function graphTierColumn<T extends EnumItem & { graph_tier?: GraphTier }>(t: TFunction, defaultTier: GraphTier, width = '25%'): EnumEditorColumn<T> {
  return {
    key: 'graph_tier',
    header: t('enumEditor.graphTier'),
    width,
    render: (item, onChange, isLocked, _isFocused, _focusRef, cell) => (
      <TextField
        select
        value={item.graph_tier || defaultTier}
        onChange={(e) => onChange({ graph_tier: e.target.value as GraphTier } as Partial<T>, 'choose')}
        size="small"
        fullWidth
        disabled={isLocked}
        sx={tableCellTextFieldSx}
        SelectProps={{ SelectDisplayProps: { 'aria-label': `${t('enumEditor.graphTier')} ${cell?.shownName ?? item.label}` } as React.HTMLAttributes<HTMLDivElement> }}
      >
        {GRAPH_TIERS.map((tier) => (
          <MenuItem key={tier} value={tier}>
            {t(`enumEditor.graphTiers.${tier}`)}
          </MenuItem>
        ))}
      </TextField>
    ),
  };
}

const buildDefaultColumns = <T extends EnumItem>(t: TFunction, placeholder?: string): EnumEditorColumn<T>[] => [nameColumn<T>(t, '55%', placeholder), retiredColumn<T>(t)];

/**
 * The list editor of the settings pages (a list of values): a dense table, one row per value, its
 * columns declared by the page. The name shows what the rest of the application shows in the
 * person's language; a retyped name becomes the base name. Row actions: Translate (darker when the
 * value has a typed translation), then Delete, which asks first when records use the value. A
 * server-managed value is a line of text marked Built-in. "Add an item" under the table adds a
 * row at the bottom, the cursor in its name. Virtual scrolling for long lists.
 */
export function EnumEditor<T extends EnumItem>({
  items,
  onChange,
  onCommit,
  columns,
  lockedCodes,
  protectedCodes,
  usageList,
  defaults,
  forbidComma,
  newRow,
  hideAddButton,
  namePlaceholder,
  readOnly = false,
  addButtonLabel: addButtonLabelProp,
  onAddRequest,
  addRequestToken,
  rowHeight = 40,
  emptyMessage: emptyMessageProp,
}: EnumEditorProps<T>) {
  const { t } = useTranslation('common');
  const locale = useCatalogLocale();
  const addButtonLabel = addButtonLabelProp ?? t('settingsSection.addItem');
  const emptyMessage = emptyMessageProp ?? t('enumEditor.noValues');
  const lockedSet = React.useMemo(
    () => new Set((lockedCodes || []).map((code) => code.toLowerCase())),
    [lockedCodes]
  );
  const protectedSet = React.useMemo(
    () => new Set((protectedCodes || []).map((code) => code.toLowerCase())),
    [protectedCodes]
  );

  const itemsWithIds = React.useMemo(
    () => withLocalIds(items, 'enum'),
    [items]
  );

  // The rows go to the page with the way their change is saved.
  const howRef = React.useRef<EnumEditorChange>('type');
  const emit = React.useCallback((rows: T[]) => onChange(rows, howRef.current), [onChange]);
  const [localItems, changeRows] = useEditorRows<T>(itemsWithIds, emit);
  const change = React.useCallback((update: (current: T[]) => T[], how: EnumEditorChange) => {
    howRef.current = how;
    changeRows(update);
  }, [changeRows]);
  const [focusId, setFocusId] = React.useState<string | null>(null);
  const firstFieldRef = React.useRef<HTMLInputElement | null>(null);
  const lastAddToken = React.useRef<number | undefined>(undefined);

  const { containerRef, onScroll, useVirtual, visibleItems, paddingTop, paddingBottom, maxHeight } =
    useVirtualRows({
      items: localItems,
      rowHeight,
    });

  // The new row is at the bottom: a long list scrolls to it, then its name takes the cursor.
  React.useEffect(() => {
    if (!focusId) return;
    if (firstFieldRef.current) {
      firstFieldRef.current.focus();
      firstFieldRef.current.select();
      firstFieldRef.current = null;
      setFocusId(null);
      return;
    }
    const box = containerRef.current;
    if (box && useVirtual) box.scrollTop = box.scrollHeight;
  }, [focusId, visibleItems, useVirtual, containerRef]);

  const handleUpdate = React.useCallback(
    (localId: string, patch: Partial<T>, how: EnumEditorChange = 'type') => {
      if (readOnly) return;
      change((prev) => prev.map((item) => ((item as any).localId === localId ? { ...item, ...patch } : item)), how);
    },
    [change, readOnly]
  );

  const handleAdd = React.useCallback(() => {
    if (readOnly) return;
    const newItem = { deprecated: false, ...(newRow?.() ?? {}), code: '', label: '', localId: makeLocalId('enum') } as T;
    change((prev) => [...prev, newItem], 'type');
    setFocusId((newItem as any).localId);
  }, [change, newRow, readOnly]);

  React.useEffect(() => {
    if (addRequestToken === undefined) return;
    if (addRequestToken === lastAddToken.current) return;
    lastAddToken.current = addRequestToken;
    handleAdd();
  }, [addRequestToken, handleAdd]);

  const removeRow = React.useCallback(
    (localId: string) => {
      change((prev) => prev.filter((row) => (row as any).localId !== localId), 'choose');
    },
    [change]
  );

  // A saved value is removed only when nothing references it; otherwise the dialog offers to retire it.
  const removal = useCatalogRemoval(usageList);
  const translations = useCatalogTranslations();
  const shown = React.useCallback((item: T) => shownCatalogName(item, locale, defaults), [defaults, locale]);
  const requestRemoval = (item: T & { localId: string }) => removal.requestRemoval({
    name: shown(item) || item.code,
    key: item.code ? { code: item.code } : null,
    onRemove: () => removeRow(item.localId),
    onRetire: () => handleUpdate(item.localId, { deprecated: true } as Partial<T>, 'choose'),
  });

  const effectiveColumns = React.useMemo(() => columns || buildDefaultColumns<T>(t, namePlaceholder), [columns, namePlaceholder, t]);
  const showActions = !readOnly;
  const totalColumns = effectiveColumns.length + (showActions ? 1 : 0);
  const issues = React.useMemo(() => catalogEditorIssues(localItems, shown, { forbidComma, skipCodes: lockedSet }), [forbidComma, localItems, lockedSet, shown]);
  const issueOf = (item: T): CatalogIssue | undefined => issues.get(localItems.indexOf(item));

  return (
    <Box onBlur={onCommit}>
      <TableContainer ref={containerRef as any} onScroll={onScroll} sx={{ maxHeight }}>
        <Table size="small" stickyHeader={useVirtual} sx={tableSx}>
          <TableHead>
            <TableRow>
              {effectiveColumns.map((col) => (
                <TableCell
                  key={String(col.key)}
                  sx={{ width: col.width }}
                  align={col.align || 'left'}
                >
                  {col.header}
                  {col.required && <RequiredMark />}
                </TableCell>
              ))}
              {showActions && (
                <TableCell align="right" sx={{ width: 76 }}>
                  <Box component="span" sx={{ position: 'absolute', width: 1, height: 1, overflow: 'hidden', clip: 'rect(0 0 0 0)' }}>{t('labels.actions')}</Box>
                </TableCell>
              )}
            </TableRow>
          </TableHead>
          <TableBody>
            {useVirtual && paddingTop > 0 && (
              <TableRow>
                <TableCell colSpan={totalColumns} sx={{ p: 0, height: paddingTop, border: 0 }} />
              </TableRow>
            )}
            {localItems.length === 0 && (
              <TableRow>
                <TableCell colSpan={totalColumns}>
                  <Typography sx={{ fontSize: 13, color: 'kanap.text.secondary' }}>
                    {emptyMessage}
                  </Typography>
                </TableCell>
              </TableRow>
            )}
            {visibleItems.map((item, index) => {
              const typedItem = item as T & { localId: string };
              const code = String(typedItem.code || '').toLowerCase();
              const isLocked = lockedSet.has(code);
              const isProtected = !isLocked && protectedSet.has(code);
              const fieldLocked = readOnly || isLocked;
              const isFocused = typedItem.localId === focusId;
              const issue = issueOf(typedItem);
              const cell: EnumEditorCell = {
                shownName: shown(typedItem),
                rename: (text) => handleUpdate(typedItem.localId, renamedCatalogItem(typedItem, text, locale), 'type'),
                builtIn: isLocked,
              };

              return (
                <TableRow key={typedItem.localId || index}>
                  {effectiveColumns.map((col, colIndex) => (
                    <TableCell key={String(col.key)} align={col.align || 'left'}>
                      {col.render ? (
                        col.render(
                          typedItem,
                          (patch, how) => handleUpdate(typedItem.localId, patch, how),
                          fieldLocked,
                          isFocused && colIndex === 0,
                          (el) => {
                            if (isFocused && colIndex === 0) {
                              firstFieldRef.current = el;
                            }
                          },
                          cell,
                        )
                      ) : (
                        String((typedItem as any)[col.key] || '')
                      )}
                      {colIndex === 0 && issue && issue !== 'nameRequired' && <Typography sx={issueTextSx}>{t(`enumEditor.${issue}`)}</Typography>}
                    </TableCell>
                  ))}
                  {showActions && (
                    <TableCell align="right" sx={{ whiteSpace: 'nowrap' }}>
                      {!isLocked && typedItem.code && (
                        <Tooltip title={t('enumEditor.translate')} describeChild>
                          <IconButton
                            aria-label={`${t('enumEditor.translate')} ${cell.shownName}`}
                            sx={{ ...iconSx, color: hasTypedTranslation(typedItem) ? 'kanap.text.primary' : 'kanap.text.secondary' }}
                            onClick={() => translations.openTranslations({ item: typedItem, defaults, onSave: (next) => handleUpdate(typedItem.localId, { translations: next } as Partial<T>, 'choose') })}
                          >
                            <TranslateIcon sx={{ fontSize: 16 }} />
                          </IconButton>
                        </Tooltip>
                      )}
                      {isLocked || isProtected ? (
                        <Typography component="span" sx={{ fontSize: 12, color: 'kanap.text.tertiary', lineHeight: '26px', ml: 0.5 }} title={isProtected ? t('enumEditor.protectedHint') : undefined}>
                          {t('enumEditor.locked')}
                        </Typography>
                      ) : (
                        <Tooltip title={t('buttons.delete')} describeChild>
                          <IconButton aria-label={`${t('buttons.delete')} ${cell.shownName}`} sx={{ ...iconSx, color: 'kanap.text.secondary' }} onClick={() => void requestRemoval(typedItem)}>
                            <DeleteOutlineIcon sx={{ fontSize: 16 }} />
                          </IconButton>
                        </Tooltip>
                      )}
                    </TableCell>
                  )}
                </TableRow>
              );
            })}
            {useVirtual && paddingBottom > 0 && (
              <TableRow>
                <TableCell colSpan={totalColumns} sx={{ p: 0, height: paddingBottom, border: 0 }} />
              </TableRow>
            )}
          </TableBody>
        </Table>
      </TableContainer>
      {!readOnly && !hideAddButton && (
        <Box component="button" type="button" onClick={onAddRequest || handleAdd} sx={{ ...tealLinkSx, fontSize: 13, mt: 1 }}>
          {addButtonLabel}
        </Box>
      )}
      {removal.dialog}
      {translations.dialog}
    </Box>
  );
}

export default EnumEditor;
